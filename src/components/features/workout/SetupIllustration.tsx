const fillFor = (fill: Layer['fill']) =>
  fill === 'line' ? LINE : fill === 'active' ? color.active : fill === 'bg' ? color.bg : BODY;

// 조각마다 디자인의 위치·크기에 맞춰 경로를 옮긴다.
// (react-native-svg 는 안쪽 <Svg> 의 x·y·viewBox 를 기기에서 무시해 조각이 원점에 겹쳐 그려졌다)
const layerTransform = (layer: Layer): string => {
  const [vx, vy, vw, vh] = layer.viewBox.split(' ').map(Number);
  const sx = layer.w / vw;
  const sy = layer.h / vh;
  return `matrix(${sx} 0 0 ${sy} ${layer.x - vx * sx} ${layer.y - vy * sy})`;
};

function Layers({layers}: {layers: Layer[]}) {
  return (
    <Svg width="100%" height="100%" viewBox={`0 0 ${WIDTH} ${HEIGHT}`}>
      {layers.map((layer, index) => (
        <G key={index} transform={layerTransform(layer)}>
          <Path d={layer.d} fill={fillFor(layer.fill)} />
        </G>
      ))}
    </Svg>
  );
}

/** 반복 애니메이션: 0→1→0 을 period 동안. 동작 줄이기를 켠 기기에서는 1 로 멈춰 둔다 */
function usePulse(period: number, delay = 0) {
  const value = useRef(new Animated.Value(1)).current;
  useEffect(() => {
    let loop: Animated.CompositeAnimation | null = null;
    let cancelled = false;
    AccessibilityInfo.isReduceMotionEnabled()
      .catch(() => false)
      .then(reduce => {
        if (cancelled || reduce) {
          return;
        }
        value.setValue(0);
        loop = Animated.loop(
          Animated.sequence([
            Animated.delay(delay),
            Animated.timing(value, {toValue: 1, duration: period / 2, easing: Easing.inOut(Easing.quad), useNativeDriver: true}),
            Animated.timing(value, {toValue: 0, duration: period / 2, easing: Easing.inOut(Easing.quad), useNativeDriver: true}),
          ]),
        );
        loop.start();
      });
    return () => {
      cancelled = true;
      loop?.stop();
    };
  }, [value, period, delay]);
  return value;
}

